import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const names = ['core', 'members', 'index'];
const sources = names.map(name => read('src/' + name + '.ts'));
const hash = createHash('sha256').update(sources.join('\n')).digest('hex');
const factories = names.map((name, i) => {
  const { outputText, diagnostics } = ts.transpileModule(sources[i], {
    fileName: name + '.ts', reportDiagnostics: true,
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, strict: true },
  });
  if (diagnostics?.some(d => d.category === ts.DiagnosticCategory.Error)) throw new Error('Cannot compile ' + name);
  return JSON.stringify('./' + name + '.js') + ': function(module, exports, require) {\n' + outputText + '\n}';
});
const library = '/* Generated from the repository TypeScript library. MIT license: ../../../LICENSE\n * Source SHA-256: ' + hash + '\n * Regenerate: npm run build:web-sample. Do not edit this file. */\n(function(global) {\n"use strict";\nconst factories = {' + factories.join(',\n') + '};\nconst cache = Object.create(null);\nfunction load(id) {\n if(!Object.hasOwn(factories,id)) throw new Error("Unknown bundled module: "+id);\n if(!cache[id]) { const module={exports:{}}; cache[id]=module; factories[id](module,module.exports,load); }\n return cache[id].exports;\n}\nglobal.SSSContributions = Object.freeze(load("./index.js"));\n})(globalThis);\n';
const catalog = JSON.parse(read('data/contributions/index.json'));
const schedules = catalog.schedules.map(entry => JSON.parse(read('data/contributions/' + entry.path)));
const data = '/* Generated from data/contributions. Regenerate: npm run build:web-sample. */\nglobalThis.SSSCalculatorData = ' + JSON.stringify({ catalog, schedules }) + ';\n';
const outputs = [['samples/webcalculator/vendor/sss-contributions.js', library], ['samples/webcalculator/vendor/schedules.js', data], ['samples/webcalculator/LICENSE', read('LICENSE')]];
const check = process.argv.includes('--check');
for (const [path, content] of outputs) {
  if (check) { if (read(path) !== content) throw new Error(path + ' is stale; run npm run build:web-sample'); }
  else writeFileSync(new URL(path, root), content);
}
console.log(check ? 'Web sample bundles match library and source data.' : 'Updated browser library and all ' + schedules.length + ' schedules.');
